export const LOCALES = { "en-US": enUS, "zh-CN": zhCN } as const;
export type MessageKey = keyof typeof enUS;

export function normalizeLocale(
  value: unknown,
  systemLanguage: unknown = typeof navigator === "undefined" ? undefined : navigator.language,
): Locale {
  if (value === "en-US") return "en-US";
  if (value !== "system") return "zh-CN";
  return typeof systemLanguage === "string" && systemLanguage.toLowerCase().startsWith("en")
    ? "en-US"
    : "zh-CN";
}

export type Translate = (key: MessageKey, variables?: Record<string, string | number>) => string;

/** Creates a typed translator. Missing locale keys fall back to Simplified Chinese, then the key itself. */
export function createTranslator(locale: Locale): Translate {
  return (key, variables) => {
    const template = LOCALES[locale][key] ?? LOCALES["zh-CN"][key] ?? key;
    return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(variables?.[name] ?? `{{${name}}}`));
  };
}

/** Convert transport error codes to locale-specific, renderer-safe text. */
export function localizeAiError(error: unknown, t: Translate): string {
  const message = error instanceof Error ? error.message : String(error);
  if (message.startsWith("AI_URL_TOO_LONG")) return t("ai.error.urlTooLong");
  if (message.startsWith("AI_URL_INVALID")) return t("ai.error.urlInvalid");
  if (message.startsWith("AI_URL_PROTOCOL")) return t("ai.error.urlProtocol");
  if (message.startsWith("AI_URL_CREDENTIALS")) return t("ai.error.urlCredentials");
  if (message.startsWith("AI_URL_INSECURE")) return t("ai.error.urlInsecure");
  if (message.startsWith("AI_API_KEY_REQUIRED")) return t("ai.error.keyRequired");
  if (message.startsWith("AI_API_KEY_INVALID")) return t("ai.error.keyInvalid");
  if (message.startsWith("AI_API_KEY_TOO_LARGE")) return t("ai.error.keyTooLarge");
  if (message.startsWith("AI_STORED_KEY_NOT_FOUND")) return t("ai.error.storedKeyMissing");
  if (message.startsWith("AI_CREDENTIAL_STORE_FAILED")) return t("ai.error.credentialStore");
  if (message.startsWith("AI_PROVIDER_INVALID")) return t("ai.error.providerInvalid");
  if (message.startsWith("AI_KEY_SOURCE_INVALID")) return t("ai.error.keySource");
  if (message.startsWith("AI_MODEL_REQUIRED")) return t("ai.error.modelRequired");
  if (message.startsWith("AI_MODEL_INVALID")) return t("ai.error.modelInvalid");
  if (message.startsWith("AI_REASONING_PROTOCOL_UNSUPPORTED")) return t("ai.error.reasoningProtocolUnsupported");
  if (message.startsWith("AI_MESSAGES_INVALID")) return t("ai.error.messagesInvalid");
  if (message.startsWith("AI_IMAGE_INPUT_INVALID")) return t("ai.error.imageInputInvalid");
  if (message.startsWith("AI_IMAGE_INPUT_UNSUPPORTED")) return t("ai.error.imageInputUnsupported");
  if (message.startsWith("AI_REQUEST_TOO_LARGE")) return t("ai.error.requestTooLarge");
  if (message.startsWith("AI_CLIENT_UNAVAILABLE")) return t("ai.error.clientUnavailable");
  if (message.startsWith("AI_LOCAL_AGENT_UNSUPPORTED")) return t("ai.error.localAgentUnsupported");
  if (message.startsWith("AI_LOCAL_AGENT_UNAVAILABLE")) return t("ai.error.localAgentUnavailable");
  if (message.startsWith("AI_LOCAL_AGENT_START_FAILED")) return t("ai.error.localAgentStartFailed");
  if (message.startsWith("AI_LOCAL_AGENT_FAILED")) return t("ai.error.localAgentFailed");
  if (message.startsWith("AI_LOCAL_AGENT_TIMEOUT")) return t("ai.error.localAgentTimeout");
  if (message.startsWith("AI_REQUEST_FAILED")) return t("ai.error.requestFailed");
  if (message.startsWith("AI_TIMEOUT")) return t("ai.error.timeout");
  if (message.startsWith("AI_BUSY")) return t("ai.error.busy");
  if (message.startsWith("AI_RESPONSE_TOO_LARGE")) return t("ai.error.responseTooLarge");
  const httpStatus = message.match(/^AI_HTTP_ERROR:(\d{3})/u)?.[1];
  if (httpStatus) return t("ai.error.http", { status: httpStatus });
  if (message.startsWith("AI_RESPONSE_INVALID")) return t("ai.error.invalidResponse");
  if (message.startsWith("AI_EMPTY_RESPONSE")) return t("ai.error.emptyResponse");
  if (message.startsWith("AI_AGENT_ITERATION_LIMIT")) return t("ai.error.agentIterationLimit");
  if (message.startsWith("AI_AGENT_TURN_NOT_FOUND")) return t("ai.error.agentTurnNotFound");
  if (message.startsWith("AI_TOOL_OBSERVER_DENIED") || message.startsWith("AI_TOOL_APPROVAL_REQUIRED")) {
    return t("ai.error.permissionChanged");
  }
  if (message.startsWith("AI_TERMINAL_SCOPE_INVALID")) return t("ai.error.terminalScopeInvalid");
  if (message.startsWith("AI_TOOL_CALL_INVALID")) return t("ai.error.toolCallInvalid");
  if (message.startsWith("AI_TOOL_COMMAND_INVALID")) return t("ai.error.toolCommandInvalid");
  if (message.startsWith("AI_TOOL_RESULT_INVALID")) return t("ai.error.toolResultInvalid");
  return t("ai.requestFailed");
}

/** React helper used by renderer workspaces; locale is supplied by persisted settings. */
export function useI18n(locale: Locale = "zh-CN") {
  const translator = useMemo(() => createTranslator(locale), [locale]);
  const t = useCallback<Translate>((key, variables) => translator(key, variables), [translator]);
  return { locale, t };
}
